// Backwards compatibility mappings for any legacy imports
export const gentsFabrics = gentsFabricCards.map((c) => [c.handle, c.label])
export const ladiesFabrics = ladiesFabricCards.map((c) => [c.handle, c.label])
export const girlsFabrics = girlsFabricCards.map((c) => [c.handle, c.label])
export const boysFabrics = boysFabricCards.map((c) => [c.handle, c.label])

export default function FabricCategories({
  gender,
  brand,
  active = "",
}: {
  gender: "men" | "women" | "girls" | "boys"
  brand?: string
  active?: string
}) {
  const girlsSubMap: Record<string, string> = {
    "3pc": "girls-3pc",
    "2pc": "girls-2pc",
    silk: "girls-silk",
    "embroidery-waly": "girls-embroidery",
    printed: "girls-printed",
    linen: "girls-linen",
    dhanak: "girls-linen",
    karandi: "girls-linen",
    khaddar: "girls-linen",
  }

  const boysSubMap: Record<string, string> = {
    boski: "boys-boski",
    "wash-wear": "boys-wash-wear",
    italian: "boys-wash-wear",
    wool: "boys-wool",
    "kamalia-khaddar": "boys-khaddar",
  }

  const cards =
    gender === "men" || gender === "boys"
      ? gentsFabricCards
      : ladiesFabricCards

  const titlePrefix =
    gender === "men"
      ? "Gents"
      : gender === "women"
      ? "Ladies"
      : gender === "girls"
      ? "Girls"
      : "Boys"

  const tagLabel =
    gender === "men"
      ? "Gents Unstitched"
      : gender === "women"
      ? "Ladies Unstitched"
      : gender === "girls"
      ? "Girls Unstitched"
      : "Boys Unstitched"

  const href = (handle: string) => {
    if (brand) {
      return `/brands/${brand}?gender=${gender}${handle ? "&category=" + handle : ""}`
    }
    if (gender === "girls") {
      const target = girlsSubMap[handle] || `girls-${handle}`
      return `/categories/${target}`
    }
    if (gender === "boys") {
      const target = boysSubMap[handle] || `boys-${handle}`
      return `/categories/${target}`
    }
    return `/categories/${handle || gender}`
  }

  return (
    <section
      className="border-b border-stone-200 bg-white py-8 sm:py-12"
      aria-label={`${titlePrefix} fabric categories`}
    >
      <div className="content-container">
        {/* Header */}
        <div className="mb-6 flex flex-wrap items-end justify-between gap-4">
          <div>
            <div className="inline-flex items-center gap-2 text-[10px] font-bold uppercase tracking-[0.25em] text-[#B6975A]">
              <span>Featured Fabrics</span>
              <span>•</span>
              <span>{tagLabel}</span>
            </div>
            <h2 className="mt-1 font-serif text-2xl text-stone-900 sm:text-3xl">
              {titlePrefix} Categories
            </h2>
            <p className="mt-1 text-xs text-stone-500 sm:text-sm">
              Explore authentic unstitched cuts tailored for every seasonal occasion
            </p>
          </div>
        </div>

        {/* Categories Cards Carousel / Grid */}
        <div className="relative flex gap-4 overflow-x-auto pb-4 pt-1 no-scrollbar sm:gap-6">
          {cards.map((item) => {
            const isSelected =
              active.toLowerCase() === item.handle.toLowerCase() ||
              (gender === "girls" && girlsSubMap[item.handle]?.toLowerCase() === active.toLowerCase()) ||
              (gender === "boys" && boysSubMap[item.handle]?.toLowerCase() === active.toLowerCase())

            return (
              <LocalizedClientLink
                key={item.handle}
                href={href(item.handle)}
                aria-current={isSelected ? "page" : undefined}
                className="group relative flex w-36 shrink-0 flex-col overflow-hidden rounded-2xl border bg-stone-50 text-left transition-all duration-300 hover:-translate-y-1 hover:shadow-lg sm:w-48 lg:w-52"
                style={{
                  borderColor: isSelected ? "#B6975A" : "rgba(229, 231, 235, 0.8)",
                  boxShadow: isSelected
                    ? "0 10px 25px -5px rgba(182, 151, 90, 0.35), 0 8px 10px -6px rgba(182, 151, 90, 0.2)"
                    : undefined,
                }}
              >
                {/* Image Container with Dark Overlay */}
                <div className="relative aspect-[4/5] w-full overflow-hidden bg-stone-100">
                  <img
                    src={item.image}
                    alt={item.label}
                    loading="lazy"
                    className="h-full w-full object-cover transition-transform duration-700 ease-out group-hover:scale-105"
                  />
                  <div className="absolute inset-0 bg-gradient-to-t from-black/85 via-black/25 to-transparent" />

                  {/* Top Badge */}
                  <div className="absolute left-2.5 top-2.5 z-10">
                    <span className="rounded-full bg-black/60 px-2 py-0.5 text-[9px] font-bold uppercase tracking-wider text-white backdrop-blur-md">
                      {item.badge}
                    </span>
                  </div>

                  {/* Selection Indicator Checkmark */}
                  {isSelected && (
                    <div className="absolute right-2.5 top-2.5 z-10 flex h-6 w-6 items-center justify-center rounded-full bg-[#B6975A] text-white shadow-md">
                      <svg className="h-3.5 w-3.5" viewBox="0 0 20 20" fill="currentColor">
                        <path
                          fillRule="evenodd"
                          d="M16.707 5.293a1 1 0 010 1.414l-8 8a1 1 0 01-1.414 0l-4-4a1 1 0 011.414-1.414L8 12.586l7.293-7.293a1 1 0 011.414 0z"
                          clipRule="evenodd"
                        />
                      </svg>
                    </div>
                  )}

                  {/* Bottom Text Over Image */}
                  <div className="absolute inset-x-0 bottom-0 p-3 sm:p-4">
                    <h3 className="font-serif text-sm font-semibold text-white drop-shadow-sm sm:text-base">
                      {item.label}
                    </h3>
                    <p className="mt-0.5 line-clamp-1 text-[11px] text-stone-200 font-light">
                      {item.subtitle}
                    </p>
                  </div>
                </div>


              </LocalizedClientLink>
            )
          })}
        </div>
      </div>
    </section>
  )
}
