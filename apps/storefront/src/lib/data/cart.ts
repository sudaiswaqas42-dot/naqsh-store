export async function applyPromotions(codes: string[]) {
  const cartId = await getCartId()

  if (!cartId) {
    throw new Error("No existing cart found")
  }

  const headers = {
    ...(await getAuthHeaders()),
  }

  const normalizedCodes = Array.from(new Set(codes.map(code => code.trim().toUpperCase()).filter(Boolean)))
  return sdk.store.cart
    .update(cartId, { promo_codes: normalizedCodes }, { fields: "*promotions,*items.adjustments" }, headers)
    .then(async ({ cart }) => {
      const cartCacheTag = await getCacheTag("carts")
      revalidateTag(cartCacheTag)

      const fulfillmentCacheTag = await getCacheTag("fulfillment")
      if (fulfillmentCacheTag) revalidateTag(fulfillmentCacheTag)
      const applied = new Set((cart.promotions || []).map(promotion => promotion.code?.toUpperCase()))
      const rejected = normalizedCodes.filter(code => !applied.has(code))
      if (rejected.length) throw new Error("This code is invalid, expired, or does not apply to the items in your bag.")
      return cart
    })
    .catch(medusaError)
}

